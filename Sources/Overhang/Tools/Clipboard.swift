import AppKit
import SwiftUI

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    let id: UUID
    let kind: Kind
    var text: String?
    var imageFile: String?
    var filePaths: [String]?
    var date: Date
    var pinned: Bool

    var preview: String {
        switch kind {
        case .text: return text ?? ""
        case .image: return "Image"
        case .files:
            let names = (filePaths ?? []).map { ($0 as NSString).lastPathComponent }
            return names.joined(separator: ", ")
        }
    }
}

/// Polls the general pasteboard (macOS has no change notification) and keeps a local history.
/// Items marked concealed/transient by password managers are skipped.
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()

    @Published private(set) var items: [ClipItem] = []

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let imageDirectory = AppPaths.directory("Clipboard")
    private let storeName = "clipboard.json"
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    func start() {
        items = JSONStore.load([ClipItem].self, from: storeName) ?? []
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
    }

    private var limit: Int { max(10, UserDefaults.standard.integer(forKey: Prefs.clipboardLimit)) }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty
        {
            insert(ClipItem(id: UUID(), kind: .files, filePaths: urls.map(\.path), date: Date(), pinned: false))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        {
            insert(ClipItem(id: UUID(), kind: .text, text: string, date: Date(), pinned: false))
        } else if let image = NSImage(pasteboard: pasteboard), let png = image.pngData, png.count < 12_000_000 {
            let name = UUID().uuidString + ".png"
            try? png.write(to: imageDirectory.appendingPathComponent(name))
            insert(ClipItem(id: UUID(), kind: .image, imageFile: name, date: Date(), pinned: false))
        }
    }

    private func insert(_ item: ClipItem) {
        var list = items
        if let index = list.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.filePaths == item.filePaths && item.kind != .image }) {
            var existing = list.remove(at: index)
            existing.date = item.date
            list.insert(existing, at: 0)
        } else {
            list.insert(item, at: 0)
        }
        // Trim oldest unpinned items beyond the limit.
        while list.count > limit, let index = list.lastIndex(where: { !$0.pinned }) {
            removeFiles(of: list.remove(at: index))
        }
        items = list
        save()
    }

    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        case .files:
            pasteboard.writeObjects((item.filePaths ?? []).map { NSURL(fileURLWithPath: $0) })
        }
        lastChangeCount = pasteboard.changeCount
        if let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        return NSImage(contentsOf: imageDirectory.appendingPathComponent(name))
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeFiles(of: item)
        save()
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(removeFiles)
        items.removeAll { !$0.pinned }
        save()
    }

    private func removeFiles(of item: ClipItem) {
        if let name = item.imageFile {
            try? FileManager.default.removeItem(at: imageDirectory.appendingPathComponent(name))
        }
    }

    private func save() { JSONStore.save(items, to: storeName) }
}

extension NSImage {
    var pngData: Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}

struct ClipboardView: View {
    @ObservedObject private var service = ClipboardService.shared
    @State private var query = ""
    @State private var toast: String?

    private var filtered: [ClipItem] {
        let sorted = service.items.filter(\.pinned) + service.items.filter { !$0.pinned }
        guard !query.isEmpty else { return sorted }
        return sorted.filter { $0.preview.localizedCaseInsensitiveContains(query) }
    }

    var body: some View {
        VStack(spacing: 8) {
            HStack {
                InputField(placeholder: "Search clipboard", text: $query, symbol: "magnifyingglass")
                PillButton(title: "Clear", symbol: "trash") { service.clearUnpinned() }
            }
            if filtered.isEmpty {
                EmptyState(symbol: "doc.on.clipboard", title: query.isEmpty ? "Clipboard is empty" : "No matches",
                           message: query.isEmpty ? "Copy something and it shows up here. Password-manager copies are skipped." : "")
            } else {
                ScrollView {
                    LazyVStack(spacing: 4) {
                        ForEach(filtered) { item in
                            ClipRow(item: item) {
                                service.copy(item)
                                withAnimation { toast = "Copied" }
                            }
                        }
                    }
                }
            }
        }
        .toast($toast)
    }
}

private struct ClipRow: View {
    let item: ClipItem
    let onCopy: () -> Void
    @State private var hovering = false

    var body: some View {
        HStack(spacing: 10) {
            thumbnail
            Text(item.preview.trimmingCharacters(in: .whitespacesAndNewlines))
                .font(.system(size: 12))
                .lineLimit(2)
                .frame(maxWidth: .infinity, alignment: .leading)
            if hovering || item.pinned {
                IconButton(symbol: item.pinned ? "pin.fill" : "pin", size: 22, tint: item.pinned ? Theme.accent : .white) {
                    ClipboardService.shared.togglePin(item)
                }
            }
            if hovering {
                IconButton(symbol: "xmark", size: 22) { ClipboardService.shared.delete(item) }
            } else {
                Text(item.date, style: .relative)
                    .font(.system(size: 10)).foregroundStyle(Theme.tertiary)
                    .frame(width: 70, alignment: .trailing)
            }
        }
        .padding(.horizontal, 10)
        .padding(.vertical, 6)
        .background(RoundedRectangle(cornerRadius: 9, style: .continuous).fill(hovering ? Theme.cardHover : Theme.card))
        .contentShape(Rectangle())
        .onHover { hovering = $0 }
        .onTapGesture(perform: onCopy)
    }

    @ViewBuilder private var thumbnail: some View {
        switch item.kind {
        case .text:
            Image(systemName: "text.alignleft").frame(width: 24).foregroundStyle(Theme.secondary)
        case .files:
            Image(systemName: "doc").frame(width: 24).foregroundStyle(Theme.secondary)
        case .image:
            if let image = ClipboardService.shared.image(for: item) {
                Image(nsImage: image).resizable().aspectRatio(contentMode: .fill)
                    .frame(width: 24, height: 24).clipShape(RoundedRectangle(cornerRadius: 4))
            } else {
                Image(systemName: "photo").frame(width: 24)
            }
        }
    }
}
